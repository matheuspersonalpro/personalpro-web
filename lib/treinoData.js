/** Comparação tolerante a acento/caixa/espaço — os nomes vêm de fontes variadas. */
const normalizar = (s) => String(s || '')
  .normalize('NFD').replace(new RegExp('[' + String.fromCharCode(0x0300) + '-' + String.fromCharCode(0x036F) + ']', 'g'), '')
  .toLowerCase().trim().replace(/\s+/g, ' ');

const SEM_CARGA_NORM = new Set([...SEM_CARGA_EXTERNA].map(normalizar));

/** true se o exercício é de peso corporal (não dá pra reduzir carga). */
export function ehPesoCorporal(nomeExercicio) {
  return SEM_CARGA_NORM.has(normalizar(nomeExercicio));
}
