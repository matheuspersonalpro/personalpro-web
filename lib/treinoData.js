// Nome ATUAL do grupo para um nome possivelmente antigo (exercício próprio criado antes da
// renomeação). Sem isso o exercício some da aba do grupo atual.
export function grupoAtual(g) {
  if (!g) return g;
  for (const [atual, antigos] of Object.entries(GRUPO_ALIASES)) {
    if (atual === g || antigos.includes(g)) return atual;
  }
  return g;
}
